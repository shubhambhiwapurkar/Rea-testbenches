"""Generates Web/js/simLayout.js from the IO_FIELDS list in SummitBridge.cpp.

The C++ list is the single source of truth for the order of the doubles shared between the game and
the simulation, so the JavaScript indices can never drift from it.
"""

import pathlib
import re
import sys


def main() -> None:
    root = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[2]
    source = (root / "Web/bridge/SummitBridge.cpp").read_text()
    block = source[source.index("#define IO_FIELDS(X)"):source.index("enum Io : int")]
    names = re.findall(r"X\((\w+)\)", block)
    lines = [
        "// Generated by Web/bridge/gen_layout.py from IO_FIELDS in SummitBridge.cpp. Do not edit.",
        "export const IO = Object.freeze({",
    ]
    lines += [f"  {name}: {index}," for index, name in enumerate(names)]
    lines += ["});", f"export const IO_COUNT = {len(names)};", ""]
    (root / "Web/js/simLayout.js").write_text("\n".join(lines))
    print(f"simLayout.js: {len(names)} fields")


if __name__ == "__main__":
    main()
